const flagCodes = { fr: "fr", en: "gb", it: "it", es: "es" };

let currentLang = localStorage.getItem("portfolio-lang") || "fr";

function applyLanguage(lang) {
  if (!translations[lang]) return;

  currentLang = lang;
  window.currentLang = lang;
  localStorage.setItem("portfolio-lang", lang);
  document.documentElement.lang = lang;
  document.body.classList.remove("lang-fr", "lang-en", "lang-it", "lang-es");
  document.body.classList.add("lang-" + lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key] !== undefined) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang][key] !== undefined) {
      el.placeholder = translations[lang][key];
    }
  });

  const currentFlag = document.getElementById("lang-current-flag");
  const currentCode = document.getElementById("lang-current-code");
  if (currentFlag) currentFlag.src = `https://flagcdn.com/w40/${flagCodes[lang]}.png`;
  if (currentCode) currentCode.textContent = lang.toUpperCase();

  document.querySelectorAll(".lang-option").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang } }));
}

window.translations = translations;
window.currentLang = currentLang;
window.applyLanguage = applyLanguage;

document.addEventListener("click", (e) => {
  const switcher = document.getElementById("lang-switcher");
  const menu = document.getElementById("lang-menu");
  if (!switcher || !menu) return;

  if (switcher.contains(e.target)) {
    if (e.target.closest("#lang-toggle")) {
      const isOpen = menu.classList.toggle("open");
      document.getElementById("lang-toggle").setAttribute("aria-expanded", isOpen);
    }
    const option = e.target.closest(".lang-option");
    if (option) {
      applyLanguage(option.getAttribute("data-lang"));
      menu.classList.remove("open");
      document.getElementById("lang-toggle").setAttribute("aria-expanded", "false");
    }
  } else {
    menu.classList.remove("open");
    const toggle = document.getElementById("lang-toggle");
    if (toggle) toggle.setAttribute("aria-expanded", "false");
  }
});

applyLanguage(currentLang);
